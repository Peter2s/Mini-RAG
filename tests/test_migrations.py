"""Alembic migrations: they match the models, and they can be undone and redone."""

import asyncio
import uuid
from collections.abc import Iterator

import pytest
from alembic import command
from alembic.util.exc import AutogenerateDiffsDetected
from sqlalchemy import Engine, make_url, text

from app.db import Database
from tests.conftest import alembic_config


@pytest.fixture
def scratch_database(postgres_admin: tuple[Engine, str]) -> Iterator[str]:
    """An empty database, dropped afterwards."""
    engine, server_url = postgres_admin
    name = f"mini_rag_migrations_{uuid.uuid4().hex[:12]}"
    with engine.connect() as connection:
        connection.execute(text(f'CREATE DATABASE "{name}"'))
    yield make_url(server_url).set(database=name).render_as_string(hide_password=False)
    with engine.connect() as connection:
        connection.execute(text(f'DROP DATABASE "{name}" WITH (FORCE)'))


def test_models_and_migrations_match(database_url):
    """Fails when a model changes without a migration: run `alembic revision --autogenerate`."""
    try:
        command.check(alembic_config(database_url))
    except AutogenerateDiffsDetected as error:
        pytest.fail(f"Models and migrations differ:\n{error}")


def test_migrations_upgrade_downgrade_and_upgrade_again(scratch_database):
    config = alembic_config(scratch_database)
    command.upgrade(config, "head")
    command.downgrade(config, "base")
    command.upgrade(config, "head")


def test_app_refuses_an_unmigrated_database(scratch_database):
    async def start() -> None:
        database = Database(scratch_database)
        try:
            await database.init()
        finally:
            await database.close()

    with pytest.raises(RuntimeError, match="alembic upgrade head"):
        asyncio.run(start())
    command.upgrade(alembic_config(scratch_database), "head")
    asyncio.run(start())
